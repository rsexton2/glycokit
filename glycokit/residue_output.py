from glycokit.structure_io import PDB_SUFFIXES, pdb_chain_map, write_pdb
from glycokit.utils import _fmt_float, _resid_labels, pdb_atom_ids

#: max coordinate difference (A) for a repeated first frame (XTC precision)
DUPLICATE_ATOL = 0.01
_RANK_LABELS = {
    "mean": "mean",
    "max": "maximum",
    "std": "standard deviation",
    "width": "95% interval width"
}

#: max coordinate difference (A) for a repeated first frame; covers the
#: 0.001 nm rounding of GRO/XTC on both sides
DUPLICATE_ATOL = 0.02
#: display units of a time axis, largest first
_TIME_UNITS = (("us", "µs"), ("ns", "ns"), ("ps", "ps"))
#: line styles that tell residues apart when colours mean trajectories
_LINESTYLES = (
    "-", "--", ":", "-.", (0, (5, 1)), (0, (3, 1, 1, 1)), (0, (1, 3)),
    (0, (8, 2, 1, 2)))


def _part_labels(paths):
    """Legend label of each trajectory part: the file name, or run_1,
    run_2, ... (in -b order) for every part if any name repeats or a
    part has no file name."""
    names = [Path(p).name if p else None for p in paths]
    if None in names or len(set(names)) != len(names):
        return [f"run_{i + 1}" for i in range(len(names))], True
    return names, False


def _time_unit(span_ps):
    """``(factor, label)``: the largest unit in which ``span_ps`` is >= 1."""
    for unit, label in _TIME_UNITS:
        factor = mda_units.get_conversion_factor("time", "ps", unit)
        if span_ps * factor >= 1:
            return factor, label
    return 1.0, "ps"


class PlotAxis(NamedTuple):
    """x-axis of the time-series plots."""
    x: np.ndarray
    seg: np.ndarray
    keep: np.ndarray
    label: str
    names: list  # legend label of each trajectory part
    renamed: bool = False  # True: names are run_1, run_2, ...


def _reader_has_time(reader):
    """False for formats without time information (time unit None)."""
    return (getattr(reader, "units", None) or {}).get("time") is not None


def _finite_max(values, default=0.0):
    """Largest finite value, or ``default`` if there is none."""
    a = np.asarray(values, dtype=float)
    finite = a[np.isfinite(a)]
    return float(finite.max()) if finite.size else default


class ResidueOutputMixin:
    """Shared writers; mix in before AnalysisBase. Defines no instance state or
    __init__."""

    u: mda.Universe
    outdir: str | None
    n_frames: int

    #: concrete host classes, filled by __init_subclass__ (used by the tests)
    _registry = []
    #: methods every concrete host must override
    _HOOKS = ("_residue_column_atoms", "_residue_values")

    # ---------------------------------------------- per-class settings
    #: attribute name in ChimeraX .defattr files
    _output_attribute = "value"
    _vmd_script_name = "load_user_attributes.vmd"
    _vmd_header = (
        "Auto-generated by glycokit",
        "Bulk per-frame assignment of residue values")
    _vmd_error_label = "VMD script"
    _chimerax_script_name = "residue_stats.cxc"
    #: default name of write_statistics_pdb()
    _stats_pdb_name = "b_factors_stats.pdb"
    #: wording of the statistics ChimeraX script
    _stats_generator = "glycokit"
    _stats_quantity = "value"
    #: y-axis label and default file name of plot_timeseries()
    _plot_label = "value"
    _timeseries_plot_name = "residue_timeseries.png"
    _top_residues_plot_name = "top_residues.png"
    #: bin count of the marginal histograms for continuous values
    _plot_min_bins = 10
    _plot_max_bins = 60

    def __init_subclass__(cls, *, abstract=False, **kwargs):
        super().__init_subclass__(**kwargs)  # cooperative: AnalysisBase, object
        if abstract:
            return
        missing = [
            name for name in cls._HOOKS
            if getattr(cls, name) is getattr(ResidueOutputMixin, name)
        ]
        if missing:
            raise TypeError(
                f"{cls.__name__} must implement {', '.join(missing)} "
                "(or be declared with abstract=True)")
        ResidueOutputMixin._registry.append(cls)

    # -- hooks the host implements ---------------------------------------

    def _residue_column_atoms(self):
        """AtomGroup with one atom per value column (e.g. one CA per residue).
        """
        raise NotImplementedError

    def _residue_values(self):
        """Per-residue values, shape (n_frames, n_columns)."""
        raise NotImplementedError

    # -- overridable defaults --------------------------------------------

    def _require_run(self):
        if getattr(self, "frames", None) is None:
            raise RuntimeError(f"{type(self).__name__}: call run() first")

    def _error(self, message, exc=ValueError):
        raise exc(message)

    def _output_path(self, output, default_name):
        if output is not None:
            return Path(output)
        return Path(getattr(self, "outdir", None) or ".") / default_name

    def _report_written(self, label, path):
        """Called after each viewer file is written."""
        written(label, path, base=getattr(self, "outdir", None) or ".")

    def _viewer_frames(self):
        """Trajectory frame of each analyzed frame (VMD frame numbers)."""
        return [int(f) for f in self._analyzed_frames()]

    def _viewer_universe(self):
        """Universe whose files the VMD script loads."""
        return self._residue_column_atoms().universe

    def _viewer_atom_rows(self):
        """Atoms that receive values in VMD and their value column."""
        return self._residue_atom_rows()

    def _stats_bin_width(self):
        """Histogram bin width; None: one bin per integer value 0..max.

        Hosts with continuous values (e.g. SASA) override this.
        """
        return None

    # -- frame bookkeeping -----------------------------------------------

    def _analyzed_frames(self):
        """Trajectory frame index of each analyzed frame."""
        frames = getattr(self, "frames", None)
        if frames is not None and len(frames) == self.n_frames:
            return np.asarray(frames, dtype=int)
        return np.arange(self.n_frames)

    @contextlib.contextmanager
    def _at_analyzed_frame(self, k):
        """Temporarily move the trajectory to analyzed frame ``k``."""
        old = int(self.u.trajectory.frame)
        try:
            self.u.trajectory[int(self._analyzed_frames()[k])]  # pylint: disable=expression-not-assigned
            yield
        finally:
            self.u.trajectory[old]  # pylint: disable=pointless-statement

    def _resolve_frame_index(self, frame_index=None, n=None):
        """Normalize an index into the analyzed frames (None: the last)."""
        if n is None:
            n = getattr(self, "n_frames", None)
        if n is None:
            raise RuntimeError(
                "frame indices are only defined after run() started")
        n = int(n)
        if n <= 0:
            self._error(
                "no frames to analyze (check --frames/--start/--stop/--step)")
        if frame_index is None:
            return n - 1
        msg = "frame index (--bfactor-frame) must be an integer, got " \
            f"{frame_index!r}"
        if isinstance(frame_index, bool):
            self._error(msg)
        try:
            k = operator.index(frame_index)
        except TypeError:
            self._error(msg)
        if not -n <= k < n:
            self._error(
                f"frame index (--bfactor-frame) {k} is out of range for {n} "
                f"analyzed frame(s); valid values are -{n} to {n - 1}",
                exc=IndexError,
            )
        return k + n if k < 0 else k

    def _output_frame(self, frame_index):
        """``(k, trajectory_frame)`` an output is written for."""
        self._require_run()
        k = self._resolve_frame_index(frame_index)
        return k, int(self._analyzed_frames()[k])

    # -- paths, identities, CSV ------------------------------------------

    @staticmethod
    def _rows_for(residue_resindices, atom_resindices):
        """Column (position in ``residue_resindices``) of each atom's residue.
        """
        residue_resindices = np.asarray(residue_resindices)
        order = np.argsort(residue_resindices)
        pos = np.searchsorted(residue_resindices, atom_resindices, sorter=order)
        return order[pos]

    @staticmethod
    def _atom_attr(atom_group, attribute, default=""):
        try:
            values = getattr(atom_group, attribute)
        except (AttributeError, mda.exceptions.NoDataError):
            return np.full(len(atom_group), default, dtype=object)
        return np.asarray([str(v).strip() for v in values], dtype=object)

    def _identity_columns(self, atom_group, prefix="", atoms=True):
        """Columns chain, resid, resname [, atom_name, atom_serial]."""
        p = f"{prefix}_" if prefix else ""
        names = [f"{p}chain", f"{p}resid", f"{p}resname"]
        cols = [
            self._atom_attr(atom_group, "chainIDs"),
            _resid_labels(atom_group),
            self._atom_attr(atom_group, "resnames"),
        ]
        if atoms:
            names += [f"{p}atom_name", f"{p}atom_serial"]
            cols += [
                self._atom_attr(atom_group, "names"),
                pdb_atom_ids(atom_group)
            ]
        return names, cols

    def _write_csv(self, output, default_name, header, batches, label):
        """Write ``header`` and every batch of rows; returns the path."""
        output = self._output_path(output, default_name)
        n = 0
        with output.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.writer(handle)
            writer.writerow(header)
            for batch in batches:
                batch = list(batch)
                writer.writerows(batch)
                n += len(batch)
        written(label, output, n, base=self.outdir or ".")
        return output

    # -- B-factor PDB ----------------------------------------------------

    def _ensure_topology_attr(self, name):
        try:
            getattr(self.u.atoms, name)
        except (AttributeError, mda.exceptions.NoDataError):
            self.u.add_TopologyAttr(name)

    def _ensure_tempfactors(self):
        self._ensure_topology_attr("tempfactors")

    def _ensure_occupancies(self):
        self._ensure_topology_attr("occupancies")

    @staticmethod
    def _strip_placeholder_cryst1(path, dims):
        """Remove the 1 A CRYST1 MDAnalysis writes for a Universe without a box.
        """
        if dims is None or np.allclose(np.asarray(dims[:3]), 1.0):
            lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
            path.write_text(
                "".join(l for l in lines if not l.startswith("CRYST1")),
                encoding="utf-8")

    def _residue_atom_rows(self):
        """All atoms of the column residues (sorted by index) and their column.
        """
        col_atoms = self._residue_column_atoms()
        atoms = col_atoms.residues.atoms
        cols = self._rows_for(col_atoms.resindices, atoms.resindices)
        order = np.argsort(atoms.indices, kind="stable")
        return atoms[order], cols[order]

    def write_bfactors(
            self, frame_index=None, output=None, *, values=None,
            default_name="b_factors.pdb", label="B-factors"):
        """
        PDB of one frame with each residue's value as B-factor, plus a .npy
        of all frames next to it.

        Every atom of a column residue (hydrogens included) gets that
        residue's value; all other atoms get 0. The values stay set as
        ``tempfactors`` on the Universe.

        :param values: (n_frames, n_columns) array; None uses the hook.
        """
        k, _ = self._output_frame(frame_index)
        matrix = np.asarray(
            self._residue_values() if values is None else values)
        output = self._output_path(output, default_name)
        self._ensure_tempfactors()

        row = matrix[k]
        finite = row[np.isfinite(row)]
        if finite.size and finite.max() > 999.99:
            warnings.warn(
                f"max B-factor value {finite.max():g} exceeds the PDB B-factor "
                f"column width (999.99); use {output.with_suffix('.npy').name} "
                "for the raw values", stacklevel=2,
            )
        atoms, cols = self._residue_atom_rows()
        self.u.atoms.tempfactors = np.zeros(self.u.atoms.n_atoms)
        atoms.tempfactors = row[cols]

        with self._at_analyzed_frame(k):
            write_pdb(self.u.atoms, output)
            dims = self.u.dimensions
        self._strip_placeholder_cryst1(output, dims)

        np.save(output.with_suffix(".npy"), matrix)
        written(label, output, base=self.outdir or ".")
        return output

    # -- statistics over analyzed frames ---------------------------------

    def _stats_matrix(self, values):
        self._require_run()
        m = np.asarray(self._residue_values() if values is None else values)
        if m.ndim != 2:
            raise ValueError(
                f"statistics need a 2-D (frames, columns) array, got {m.shape}")
        return m

    def _bin_index(self, m):
        """Bin of every value, a finite mask, and the value of each bin."""
        finite = np.isfinite(m)
        if (m[finite] < 0).any():
            raise ValueError("residue statistics need non-negative values")
        width = self._stats_bin_width()  # pylint: disable=assignment-from-none
        clean = np.where(finite, m, 0)
        if width is None:
            if not np.array_equal(m[finite], np.round(m[finite])):
                raise ValueError(
                    f"{type(self).__name__}: non-integer values need "
                    "a bin width (override _stats_bin_width)")
            idx = clean.astype(np.int64)
            n_bins = int(idx[finite].max(initial=0)) + 1
            centres = np.arange(n_bins)  # 0..max, as before
        else:
            width = float(width)
            idx = np.floor(clean / width).astype(np.int64)
            n_bins = int(idx[finite].max(initial=0)) + 1
            centres = (np.arange(n_bins) + 0.5) * width  # bin centres
        return idx, finite, centres

    def residue_histograms(self, values=None):
        """
        ``(values, hist)``: ``hist[i, b]`` is the number of analyzed frames in
        which column ``i`` falls into bin ``b`` (bin value ``values[b]``).
        Non-finite values are ignored. Both arrays are read-only.
        """
        m = self._stats_matrix(values)
        idx, finite, centres = self._bin_index(m)
        n_cols, nb = m.shape[1], len(centres)
        cols = np.broadcast_to(np.arange(n_cols), m.shape)
        hist = np.bincount((cols * nb + idx)[finite],
                           minlength=n_cols * nb).reshape(n_cols,
                                                          nb).astype(np.int64)
        centres.flags.writeable = False
        hist.flags.writeable = False
        return centres, hist

    def residue_statistics(self, values=None, level=0.95):
        """
        Per column: ``mode`` (bin value with the most frames), ``lower`` /
        ``upper`` (equal-tailed ``level`` interval of the bin values),
        ``width`` (upper - lower) and ``n_frames`` (finite frames).
        """
        centres, hist = self.residue_histograms(values)
        n = hist.sum(axis=1)
        cum = np.cumsum(hist, axis=1)
        tail = (1.0 - level) / 2.0
        eps = 1e-9  # avoid rounding just above an integer cumulative count
        lo = np.argmax(cum >= tail * n[:, None] - eps, axis=1)
        hi = np.argmax(cum >= (1.0 - tail) * n[:, None] - eps, axis=1)
        c = centres.astype(float)
        empty = n == 0

        def pick(ix):
            return np.where(empty, np.nan, c[ix])

        lower, upper = pick(lo), pick(hi)
        return {
            "mode": pick(np.argmax(hist, axis=1)),
            "lower": lower,
            "upper": upper,
            "width": upper - lower,
            "n_frames": n,
        }

    def _bin_labels(self, centres):
        if self._stats_bin_width() is None:
            return [str(int(v)) for v in centres]
        return [f"{v:g}" for v in centres]

    def _column_identities(self):
        names, cols = self._identity_columns(
            self._residue_column_atoms(), atoms=False)
        return names, list(zip(*(c.tolist() for c in cols)))

    def write_histograms_csv(
            self, output=None, *, values=None,
            default_name="residue_histograms.csv", label="Residue histograms"):
        """One row per column residue, one column per bin value."""
        centres, hist = self.residue_histograms(values)
        names, idents = self._column_identities()
        rows = ([*ident, *h] for ident, h in zip(idents, hist.tolist()))
        return self._write_csv(
            output, default_name, [*names, *self._bin_labels(centres)], [rows],
            label)

    def write_statistics_csv(
            self, output=None, *, values=None,
            default_name="residue_statistics.csv", label="Residue statistics"):
        stats = self.residue_statistics(values)
        names, idents = self._column_identities()
        keys = ("mode", "lower", "upper", "width")
        rows = (
            [
                *ident, *(_fmt_float(stats[k][i]) for k in keys),
                int(stats["n_frames"][i])
            ] for i, ident in enumerate(idents))
        return self._write_csv(
            output, default_name, [*names, *keys, "n_frames"], [rows], label)

    def write_statistics_pdb(
            self, frame_index=None, output=None, *, values=None,
            default_name=None, label="Statistics B-factors"):
        """
        PDB with B-factor = mode and occupancy = interval width.

        :param default_name: File name in ``outdir`` when ``output`` is None;
            None: :attr:`_stats_pdb_name`.
        """
        k, _ = self._output_frame(frame_index)
        stats = self.residue_statistics(values)
        output = self._output_path(output, default_name or self._stats_pdb_name)
        self._ensure_tempfactors()
        self._ensure_occupancies()
        for name in ("mode", "width"):
            finite = stats[name][np.isfinite(stats[name])]
            if finite.size and finite.max() > 999.99:
                warnings.warn(
                    f"max {name} {finite.max():g} exceeds the PDB "
                    "column width (999.99)", stacklevel=2)
        atoms, cols = self._residue_atom_rows()
        old_bf = self.u.atoms.tempfactors.copy()
        old_occ = self.u.atoms.occupancies.copy()
        try:
            self.u.atoms.tempfactors = np.zeros(self.u.atoms.n_atoms)
            self.u.atoms.occupancies = np.zeros(self.u.atoms.n_atoms)
            atoms.tempfactors = np.nan_to_num(stats["mode"][cols])
            atoms.occupancies = np.nan_to_num(stats["width"][cols])
            with self._at_analyzed_frame(k):
                write_pdb(self.u.atoms, output)
                dims = self.u.dimensions
        finally:
            self.u.atoms.tempfactors = old_bf
            self.u.atoms.occupancies = old_occ
        self._strip_placeholder_cryst1(output, dims)
        written(label, output, base=self.outdir or ".")
        return output

    # -- plots -------------------------------------------------------------

    def _segment_info(self):
        """Parts of the (chained) trajectory: first global frame, length,
        file name, start times and duplicate first frames."""
        reader = self.u.trajectory
        readers = list(getattr(reader, "readers", None) or [reader])
        n = len(readers)
        lengths = np.array([r.n_frames for r in readers], dtype=int)

        paths = [getattr(r, "filename", None) for r in readers]
        names, renamed = _part_labels(paths)
        info = {
            "starts": np.concatenate(([0], np.cumsum(lengths)[:-1])),
            "lengths": lengths,
            "names": names,
            "paths": [str(p) if p else "" for p in paths],
            "renamed": renamed,
            "timed": all(_reader_has_time(r) for r in readers),
            "dt": np.ones(n),
            "chain_t0": np.zeros(n),
            "raw_t0": np.zeros(n),
            "duplicates": set(),
        }
        old = int(reader.frame)
        prev_xyz = prev_t = None
        try:
            for i, r in enumerate(readers):
                info["chain_t0"][i] = reader[int(info["starts"][i])].time
                ts = r[0]
                info["raw_t0"][i] = ts.time
                if info["timed"]:
                    info["dt"][i] = float(r.dt)
                if (prev_xyz is not None and np.allclose(
                        prev_xyz, ts.positions, rtol=0, atol=DUPLICATE_ATOL)):
                    info["duplicates"].add(i)
                last = r[r.n_frames - 1]
                prev_xyz, prev_t = last.positions.copy(), last.time
        finally:
            reader[old]  # pylint: disable=pointless-statement
        return info

    @staticmethod
    def _concatenated_times(t, seg, keep, info):
        """One continuous time axis (ps) built from each file's own clock."""
        raw = info["raw_t0"][seg] + (t - info["chain_t0"][seg])
        if np.all(np.diff(raw[keep]) > 0):
            return raw  # continuation runs: the file clocks already continue
        # every part restarts its clock: place the parts end to end
        n, dups = len(info["starts"]), info["duplicates"]
        offset = np.zeros(n)
        for i in range(1, n):
            span = (info["lengths"][i - 1] - 1) * info["dt"][i - 1]
            gap = 0.0 if i in dups else info["dt"][i - 1]
            offset[i] = offset[i - 1] + span + gap
        return offset[seg] + (raw - info["raw_t0"][seg])

    def _plot_axis(self, trajectories="concatenated"):
        """x-axis of the analysed frames; times scaled to ps, ns or µs."""
        if trajectories not in ("concatenated", "separate"):
            raise ValueError(
                "trajectories must be 'concatenated' or 'separate', got "
                f"{trajectories!r}")
        info = self._segment_info()
        frames = self._analyzed_frames()
        seg = np.searchsorted(info["starts"], frames, side="right") - 1
        local = frames - info["starts"][seg]
        n, dups = len(info["starts"]), info["duplicates"]
        t = self._time_values()  # None without real time information
        keep = np.ones(len(frames), dtype=bool)
        note = ""

        if n == 1:
            x, label = (t, "time ({unit})") if t is not None else (
                frames, "trajectory frame")
        elif trajectories == "separate":
            if t is not None:
                x = t - info["chain_t0"][seg]
                label = "time since segment start ({unit})"
            else:
                x, label = local, "frame within segment"
        else:
            keep = ~(np.isin(seg, sorted(dups)) & (local == 0))
            if t is not None:
                x = self._concatenated_times(t, seg, keep, info)
                label = "time ({unit}, concatenated)"
            else:
                removed = np.cumsum([i in dups for i in range(n)])
                x = frames - removed[seg]
                label = "frame (concatenated trajectory)"
            if dups:
                note = f"; {len(dups)} duplicate frame(s) removed"

        x = np.asarray(x, dtype=float)
        if t is not None:
            shown = x[keep]
            factor, unit = _time_unit(
                float(np.ptp(shown)) if shown.size else 0.0)
            x = x * factor
            label = label.format(unit=unit)
        return PlotAxis(
            x, seg, keep, label + note, info["names"], info["renamed"])

    def _residue_order(self, cols):
        """``cols`` ordered by chain, residue number and insertion code.

        Which residues are shown is still decided by rank; this only makes
        the panels read like the structure (A:ASN52, A:ASN90, B:ASN52).
        """
        cols = np.asarray(cols, dtype=int)
        atoms = self._residue_column_atoms()
        chains = self._atom_attr(atoms, "chainIDs")
        icodes = self._atom_attr(atoms, "icodes")
        try:
            resids = np.asarray(atoms.resids, dtype=np.int64)
        except (AttributeError, mda.exceptions.NoDataError):
            resids = np.asarray(atoms.resindices, dtype=np.int64)

        def key(c):
            return (str(chains[c]), int(resids[c]), str(icodes[c]))

        return np.asarray(sorted(cols.tolist(), key=key), dtype=int)

    @staticmethod
    def _legend_height(fontsize="small"):
        """Height (inches) of a legend with a title row and one entry row."""
        from matplotlib.font_manager import (
            FontProperties,  # pylint: disable=import-outside-toplevel
        )
        fs = FontProperties(size=fontsize).get_size_in_points()
        # two text rows plus border padding and frame: about 5 font sizes
        return 5.0 * fs / 72.0

    def _trajectory_legend(
            self, parent, axis, used, colors, loc="outside lower center"):
        """Legend with one colour per trajectory file: the title in the
        first row, all entries in the second (width follows the entries)."""
        from matplotlib.lines import (
            Line2D,  # pylint: disable=import-outside-toplevel
        )
        title = (
            "trajectory (run_n = n-th -b/--traj file)"
            if axis.renamed else "trajectory")
        return parent.legend(
            handles=[
                Line2D([], [], color=colors[s], label=axis.names[s])
                for s in used
            ], title=title, loc=loc, ncols=len(used), fontsize="small",
            title_fontsize="small")

    def _write_run_labels(self, axis, output):
        """run_n -> file path table next to the plot (renamed labels only)."""
        if not axis.renamed:
            return None
        info = self._segment_info()
        path = Path(output).with_name("trajectory_runs.csv")
        rows = [
            [name, p, int(n)]
            for name, p, n in zip(axis.names, info["paths"], info["lengths"])
        ]
        return self._write_csv(
            path, path.name, ["label", "file", "n_frames"], [rows],
            "Trajectory run labels")

    @staticmethod
    def _part_colors(n):
        import matplotlib.pyplot as plt  # pylint: disable=import-outside-toplevel
        cycle = plt.rcParams["axes.prop_cycle"].by_key()["color"]
        return [cycle[i % len(cycle)] for i in range(n)]

    def top_residues(self, n=9, rank="mean", *, values=None, keep=None):
        """Column indices of the ``n`` residues with the highest ``rank``
        over the analysed frames (``keep``: frames to use)."""
        if rank not in _RANK_LABELS:
            raise ValueError(f"rank must be one of {sorted(_RANK_LABELS)}")
        m = np.asarray(
            self._residue_values() if values is None else values, dtype=float)
        if keep is not None:
            m = m[keep]
        if rank == "width":
            score = self.residue_statistics(values=m)["width"]
        else:
            with warnings.catch_warnings():  # all-NaN residues
                warnings.simplefilter("ignore", RuntimeWarning)
                score = {
                    "mean": np.nanmean,
                    "max": np.nanmax,
                    "std": np.nanstd
                }[rank](m, axis=0)
        score = np.where(np.isfinite(score), score, -np.inf)
        return np.argsort(-score, kind="stable")[:n]

    def plot_top_residues(
            self, output=None, *, n=9, rank="mean", trajectories="concatenated",
            values=None, sharey=False, figsize=(13.0, 8.0), dpi=150):
        """
        Time series of the ``n`` (at most 9) residues with the highest
        ``rank`` on a 3x3 grid, each with a horizontal histogram of the
        shown frames in its right margin (requires matplotlib).

        :param str trajectories: ``'concatenated'`` (one continuous x-axis,
            duplicate first frames of chained parts removed) or
            ``'separate'`` (x from each file's start).
        :param str rank: ``'mean'``, ``'max'``, ``'std'`` or ``'width'``.
        :param bool sharey: One y-range for all panels.
        :param output: Default ``<outdir>/<_top_residues_plot_name>``.
        :rtype: pathlib.Path
        """
        import matplotlib.pyplot as plt  # pylint: disable=import-outside-toplevel

        self._require_run()
        if not 1 <= n <= 9:
            raise ValueError(f"n must be 1 to 9 (3x3 grid), got {n}")
        m = np.asarray(
            self._residue_values() if values is None else values, dtype=float)
        if m.ndim != 2 or len(m) != self.n_frames:
            raise ValueError(
                f"values must be ({self.n_frames}, n_columns), got {m.shape}")

        axis = self._plot_axis(trajectories)
        cols = self._residue_order(
            self.top_residues(n, rank, values=m, keep=axis.keep))
        _, idents = self._column_identities()

        parts = [
            np.flatnonzero((axis.seg == s) & axis.keep)
            for s in range(len(axis.names))
        ]
        used = [s for s, idx in enumerate(parts) if idx.size]
        colors = self._part_colors(len(axis.names))

        multi = len(used) > 1
        fig = plt.figure(layout="constrained", figsize=figsize)
        if multi:  # panels above, a separate strip for the legend below
            leg_h = self._legend_height()
            panels, legend_fig = fig.subfigures(
                2, 1, height_ratios=(figsize[1] - leg_h, leg_h))
        else:
            panels, legend_fig = fig, None
        grid = panels.subplots(3, 6, width_ratios=(4, 1) * 3, squeeze=False)
        series, hists = grid[:, 0::2], grid[:, 1::2]
        first = series[0, 0]

        for k, (ax, hax) in enumerate(zip(series.flat, hists.flat)):
            if k >= len(cols):
                ax.set_visible(False)
                hax.set_visible(False)
                continue
            if k:
                ax.sharex(first)
                if sharey:
                    ax.sharey(first)
            hax.sharey(ax)

            c = cols[k]
            y = m[:, c]
            for s in used:
                idx = parts[s]
                ax.plot(
                    axis.x[idx], y[idx], lw=1, color=colors[s],
                    marker="o" if idx.size < 2 else None)
            self._panel_histogram(
                hax, y, parts, used, colors, self._hist_edges(y[axis.keep]))
            hax.tick_params(axis="y", labelleft=False)
            hax.tick_params(axis="x", labelsize="x-small")

            chain, resid, resname = idents[c]
            ax.set_title(
                f"{chain}:{resname}{resid}" if chain else f"{resname}{resid}",
                fontsize="medium")

        # x tick labels only under the lowest visible panel of each column
        for j in range(3):
            rows = [i for i in range(3) if 3 * i + j < len(cols)]
            for i in rows[:-1]:
                series[i, j].tick_params(labelbottom=False)
            if rows:
                hists[rows[-1], j].set_xlabel("frames", fontsize="x-small")

        panels.supxlabel(axis.label)
        panels.supylabel(self._plot_label)
        fig.suptitle(
            f"{len(cols)} residues with the highest "
            f"{_RANK_LABELS[rank]} {self._plot_label} (in residue order)")
        if multi:
            self._trajectory_legend(
                legend_fig, axis, used, colors, loc="center")

        output = self._output_path(output, self._top_residues_plot_name)
        fig.savefig(output, dpi=dpi, bbox_inches="tight")
        plt.close(fig)
        self._write_run_labels(axis, output)
        written("Top residues plot", output, base=self.outdir or ".")
        return output

    def _time_values(self):
        """Times (ps) of the analysed frames, or None if the trajectory has
        no time information (e.g. PDB/GRO: reader time unit None, so
        MDAnalysis made up frame * 1 ps)."""
        times = getattr(self, "times", None)
        if times is None or len(times) != self.n_frames:
            return None
        reader = self.u.trajectory
        readers = getattr(reader, "readers", None) or [reader]  # ChainReader
        if any((getattr(r, "units", None) or {}).get("time") is None
               for r in readers):
            return None
        t = np.asarray(times, dtype=float)
        if len(t) < 2 or not np.all(np.isfinite(t)) or np.ptp(t) == 0:
            return None
        return t

    def _plot_x(self, x):
        """x values and axis label of the time-series plot."""
        if x == "auto":
            t = self._time_values()
            if t is not None:
                return t, "time (ps)"
            return self._analyzed_frames(), "trajectory frame"
        if x == "frame":
            return self._analyzed_frames(), "trajectory frame"
        if x == "time":
            t = self._time_values()
            if t is None:
                raise ValueError(
                    "the trajectory has no time information (or a single "
                    "analysed frame); use x='frame' or x='auto'")
            return t, "time (ps)"
        raise ValueError(f"x must be 'auto', 'frame' or 'time', got {x!r}")

    def _hist_edges(self, values):
        """Bin edges of a marginal histogram, limited to the data.

        Integer values (no stats bin width): one bin per whole number.
        Continuous values: the stats bin width divided by a whole number k,
        so the edges of residue_histograms() are kept, with at least
        _plot_min_bins and at most _plot_max_bins bins over the data.
        """
        a = np.asarray(values, dtype=float)
        finite = a[np.isfinite(a)]
        if not finite.size:
            return np.array([-0.5, 0.5])
        lo, hi = float(finite.min()), float(finite.max())
        width = self._stats_bin_width()  # pylint: disable=assignment-from-none
        if width is None:  # discrete counts
            return np.arange(np.floor(lo), np.floor(hi) + 2) - 0.5

        width = float(width)
        span = hi - lo
        k = 1
        if span > 0:
            target = max(1, min(self._plot_min_bins, finite.size))
            h_auto = float(
                np.diff(np.histogram_bin_edges(finite, bins="auto"))[0])
            h = min(h_auto, span / target)
            k = max(1, int(np.ceil(width / h)))
            k = min(k, max(1, int(self._plot_max_bins * width / span)))
        # integer bin indices on the grid width / k, so edges align exactly
        i0 = int(np.floor(lo * k / width))
        i1 = int(np.floor(hi * k / width))
        return np.arange(i0, i1 + 2) * (width / k)

    @staticmethod
    def _reduce_columns(m, reduce):
        """Per-frame sum or mean over columns; NaN where no value is finite."""
        finite = np.isfinite(m)
        total = np.where(finite, m, 0.0).sum(axis=1)
        n = finite.sum(axis=1)
        if reduce == "mean":
            total = total / np.maximum(n, 1)
        return np.where(n > 0, total, np.nan)

    @staticmethod
    def _panel_histogram(hax, y, parts, used, colors, bins):
        """Horizontal histogram of ``y`` (shown frames), stacked by file."""
        data = [y[parts[s]][np.isfinite(y[parts[s]])] for s in used]
        if not any(d.size for d in data):
            return
        if len(used) > 1:
            hax.hist(
                data, bins=bins, orientation="horizontal", stacked=True,
                histtype="stepfilled", alpha=0.6,
                color=[colors[s] for s in used])
        else:
            hax.hist(
                data[0], bins=bins, orientation="horizontal",
                histtype="stepfilled", alpha=0.6, color=colors[used[0]])

    def plot_timeseries(
            self, residues=None, output=None, *, values=None, reduce="sum",
            trajectories="concatenated", max_residues=8, figsize=(8.0, 4.0),
            dpi=150):
        """
        Line plot of the per-residue quantity over the analysed frames, with
        a horizontal histogram in the right margin (requires matplotlib).

        Several trajectory files get one colour each and a legend; residues
        are then told apart by line style. Duplicate first frames are left
        out when ``trajectories='concatenated'``.

        :param residues: Column indices; None: the per-frame ``reduce``.
        :param str trajectories: ``'concatenated'`` or ``'separate'``.
        :rtype: pathlib.Path
        """
        import matplotlib.pyplot as plt  # pylint: disable=import-outside-toplevel
        from matplotlib.lines import (
            Line2D,  # pylint: disable=import-outside-toplevel
        )

        self._require_run()
        m = np.asarray(
            self._residue_values() if values is None else values, dtype=float)
        if m.ndim != 2:
            raise ValueError(
                f"values must be (n_frames, n_columns), got {m.shape}")
        axis = self._plot_axis(trajectories)
        if len(axis.x) != len(m):
            raise ValueError(
                f"{len(m)} rows of values for {len(axis.x)} frames")

        if residues is None:
            if reduce not in ("sum", "mean"):
                raise ValueError(
                    f"reduce must be 'sum' or 'mean', got {reduce!r}")
            series = [
                (
                    f"{reduce} over {m.shape[1]} residues",
                    self._reduce_columns(m, reduce))
            ]
            bins = "auto"
        else:
            cols = np.atleast_1d(np.asarray(residues, dtype=int))
            if cols.size == 0 or cols.size > max_residues:
                raise ValueError(
                    f"give 1 to {max_residues} residues, got {cols.size}")
            if cols.min() < -m.shape[1] or cols.max() >= m.shape[1]:
                raise ValueError(
                    f"residue indices out of range for {m.shape[1]} columns")
            _, idents = self._column_identities()
            series = [
                (f"{idents[i][0]}:{idents[i][2]}{idents[i][1]}", m[:, i])
                for i in cols.tolist()
            ]
            bins = self._hist_edges(m[np.ix_(axis.keep, cols)])

        parts = [
            np.flatnonzero((axis.seg == s) & axis.keep)
            for s in range(len(axis.names))
        ]
        used = [s for s, idx in enumerate(parts) if idx.size]
        multi = len(used) > 1
        colors = self._part_colors(max(len(axis.names), len(series)))
        single = len(series) == 1

        fig, axs = plt.subplot_mosaic(
            [["series", "hist"]], width_ratios=(4, 1), sharey=False,
            layout="constrained", figsize=figsize)
        ax, hax = axs["series"], axs["hist"]

        for r, (label, y) in enumerate(series):
            for s in used:  # one line per file: no line joins two files
                idx = parts[s]
                color = colors[s] if multi else colors[r]
                ls = _LINESTYLES[r % len(_LINESTYLES)] if multi else "-"
                ax.plot(
                    axis.x[idx], y[idx], lw=1, ls=ls, color=color,
                    marker="o" if idx.size < 2 else None,
                    label=None if multi else label)

        if multi and single:  # stacked histogram, coloured by trajectory
            y = series[0][1]
            data = [y[parts[s]][np.isfinite(y[parts[s]])] for s in used]
            hax.hist(
                data, bins=bins, orientation="horizontal", stacked=True,
                histtype="stepfilled", alpha=0.6,
                color=[colors[s] for s in used])
        else:
            for r, (_, y) in enumerate(series):
                finite = y[axis.keep][np.isfinite(y[axis.keep])]
                if finite.size:
                    hax.hist(
                        finite, bins=bins, orientation="horizontal",
                        color="0.3" if multi else colors[r],
                        linestyle=_LINESTYLES[r % len(_LINESTYLES)] if multi
                        else "-", histtype="stepfilled" if single else "step",
                        alpha=0.5 if single else 1.0)

        ax.set_xlabel(axis.label)
        ax.set_ylabel(self._plot_label)
        hax.set_xlabel("frames")
        hax.tick_params(axis="y", labelleft=False)
        if multi:
            self._trajectory_legend(fig, axis, used, colors)
            if single:
                ax.set_title(series[0][0], fontsize="medium")
            else:
                ax.legend(
                    handles=[
                        Line2D(
                            [], [], color="0.3",
                            ls=_LINESTYLES[r % len(_LINESTYLES)], label=label)
                        for r, (label, _) in enumerate(series)
                    ], title="residue", fontsize="small")
        else:
            ax.legend(fontsize="small")

        output = self._output_path(output, self._timeseries_plot_name)
        fig.savefig(output, dpi=dpi)
        plt.close(fig)
        written("Time series plot", output, base=self.outdir or ".")
        return output

    # -- ChimeraX plans ----------------------------------------------------

    def _chimerax_plan(self, structure, output, values, frame, attribute):
        """``(structure, keywords for viewer_scripts.write_chimerax_script)``.

        Trajectory statistics by default; explicit ``values`` or
        ``attribute`` colour by a residue attribute instead.
        """
        if values is not None or attribute is not None:
            return self._attribute_plan(
                structure, output, values, frame, attribute)
        return self._statistics_plan(structure)

    def _statistics_plan(self, structure):
        """B-factor = histogram maximum, occupancy = 95% interval width."""
        if structure is None:
            structure = self.write_statistics_pdb()
        stats = self.residue_statistics()
        bmax = max(_finite_max(stats["mode"]), 1.0)  # avoid an empty range
        if _finite_max(stats["width"]) == 0:
            warnings.warn(
                "all interval widths are 0 (e.g. a single analyzed frame); "
                "the worm has a constant radius", stacklevel=4,
            )
        return structure, {
            "color_attribute":
            "bfactor",
            "color_range": (0, bmax),
            "worm_attribute":
            "occupancy",
            "comments": (
                f"Auto-generated by {self._stats_generator}: trajectory statistics",
                f"B-factor  = histogram maximum, colored white (0) -> red ({bmax:g})",  # pylint: disable=line-too-long
                f"occupancy = width of the 95% interval of the "
                f"{self._stats_quantity}",
            ),
        }

    def _attribute_plan(self, structure, output, values, frame, attribute):
        """Colour by one residue attribute, written to a .defattr file next
        to ``output``, from ``values`` or analysed frame ``frame``."""
        attribute = attribute or self._output_attribute
        if values is None:
            values = np.asarray(self._residue_values())[frame]
        if structure is None:
            try:
                structure = vs.topology_file(
                    self._viewer_universe(), "ChimeraX script")
            except (ValueError, FileNotFoundError) as exc:
                self._error(str(exc), exc=type(exc))
                raise  # only reached if _error returns

        chain_map = None
        if Path(structure).suffix.lower() in PDB_SUFFIXES:
            chain_map, _ = pdb_chain_map(
                self._atom_attr(self.u.atoms, "chainIDs").tolist())
        attr_file = vs.write_defattr(
            Path(output).with_suffix(".defattr"), self._residue_column_atoms(),
            values, attribute, chain_map=chain_map)
        self._report_written("ChimeraX attributes", attr_file)
        return structure, {
            "color_attribute":
            attribute,
            "attribute_files": [attr_file],
            "comments": (
                f"Auto-generated by {self._stats_generator}: residue "
                f"attribute {attribute}", ),
        }

    # -- public viewer writers -------------------------------------------

    def write_vmd_user_script(
            self, output=None, frame_offset=0, values=None, frames=None):
        """
        VMD Tcl script assigning per-residue values to ``user`` for every
        analyzed frame. Every atom of a column residue gets that residue's
        value (the same mapping as the B-factor PDB).

        :param output: Default ``<outdir>/<_vmd_script_name>``.
        :param int frame_offset: Added to each trajectory frame index.
        :param values: Default :meth:`_residue_values`. A 1-D array (one
            value per column) is assigned to every frame.
        :param frames: Trajectory frame of each row; default the analysed
            frames.
        :rtype: pathlib.Path
        :raises RuntimeError: Before :meth:`run`, or if the hook values do
            not match the column atoms.
        :raises ValueError: Bad ``values``, or the file names are unknown.
        :raises FileNotFoundError: Missing topology / trajectory.
        """
        self._require_run()
        n_cols = len(self._residue_column_atoms())
        if frames is None:
            frames = self._viewer_frames()
        vals = np.asarray(self._residue_values() if values is None else values)
        if vals.ndim == 1:
            vals = np.broadcast_to(vals, (len(frames), vals.shape[0]))
        if vals.ndim != 2 or vals.shape[1] != n_cols:
            exc = RuntimeError if values is None else ValueError
            raise exc(
                f"values have shape {vals.shape}; expected "
                f"(n_frames, {n_cols})")

        atoms, columns = self._viewer_atom_rows()
        output = self._output_path(output, self._vmd_script_name)
        universe = self._viewer_universe()
        structure = (
            output.with_name(vs.vmd_structure_name(output.name))
            if vs.needs_vmd_structure(universe) else None)
        try:
            output = vs.write_vmd_user_script(
                output, atoms, vals, frames, columns=columns, universe=universe,
                frame_offset=frame_offset, header=self._vmd_header,
                label=self._vmd_error_label, structure_out=structure)
        except (ValueError, FileNotFoundError) as exc:
            self._error(str(exc), exc=type(exc))
            raise  # only reached if _error returns
        if structure is not None:
            self._report_written("VMD structure", structure)
        self._report_written("VMD script", output)
        return output

    def write_chimerax_script(
            self, structure=None, output=None, palette="white:red",
            worm_radii=(0.25, 2.0), background_color="lightgray", *,
            values=None, frame=-1, attribute=None):
        """
        ChimeraX command script (.cxc).

        By default it colours by the trajectory statistics (B-factor =
        histogram maximum, worm radius = interval width) of
        :meth:`write_statistics_pdb`. With ``values`` or ``attribute`` it
        colours by a residue attribute instead (see :meth:`_attribute_plan`).

        :param structure: Structure opened as model #1; None: the
            statistics PDB (written first), or the topology file for the
            attribute plan.
        :param output: Default ``<outdir>/<_chimerax_script_name>``.
        :param values: One value per column for the attribute plan.
        :param int frame: Analysed frame used when ``attribute`` is given
            without ``values``.
        :param str attribute: Attribute name; default
            :attr:`_output_attribute`.
        :rtype: pathlib.Path
        :raises RuntimeError: Before :meth:`run`.
        :raises FileNotFoundError: Missing structure.
        """
        self._require_run()
        output = self._output_path(output, self._chimerax_script_name)
        structure, plan = self._chimerax_plan(
            structure, output, values, frame, attribute)
        structure = Path(structure).resolve()
        if not structure.is_file():
            self._error(
                f"ChimeraX script: structure not found: {structure}",
                exc=FileNotFoundError)
        output = vs.write_chimerax_script(
            output, structure, palette=palette, worm_radii=worm_radii,
            background_color=background_color, **plan)
        self._report_written("ChimeraX script", output)
        return output
