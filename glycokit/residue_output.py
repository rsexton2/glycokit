"""
Per-residue output writers shared by GlycoAnalysis and FreesasaAnalysis.

:class:`ResidueOutputMixin` adds frame bookkeeping, B-factor and statistics
PDB writers, CSV writers, and VMD / ChimeraX scripts to an AnalysisBase
subclass. The host class must provide:

* ``u`` (Universe), ``outdir`` (str or None)
* ``n_frames`` / ``frames`` (set by ``AnalysisBase.run``)
* :meth:`_residue_column_atoms`: one atom per value column
* :meth:`_residue_values`: values, shape (n_frames, n_columns)

Everything else has a default that a host may override (see the
"per-class settings" and "overridable defaults" sections).
"""

