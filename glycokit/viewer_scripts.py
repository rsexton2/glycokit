"""VMD and ChimeraX scripts for per-residue values.

Plain functions, so any module can write any values. GlycoAnalysis wraps
them in write_vmd_user_script() and write_chimerax_script().
"""
# pylint: disable=too-many-arguments,too-many-locals
import math
import re
from pathlib import Path

import numpy as np
from MDAnalysis.exceptions import NoDataError

from glycokit.structure_io import write_pdb

__all__ = [
    "index_ranges", "residue_atom_rows", "tcl_quote", "topology_file",
    "trajectory_files", "write_chimerax_script", "write_defattr",
    "write_vmd_user_script",
]

#: Structure formats VMD reads reliably, by extension. .tpr is left out on
#: purpose: VMD's GROMACS plugin only reads some TPR versions.
VMD_TOPOLOGY_SUFFIXES = frozenset(
    {".pdb", ".ent", ".psf", ".gro", ".pqr", ".mol2", ".prmtop", ".parm7"})

# ---------------------------------------------------------------- helpers


def vmd_readable(path):
    """True if VMD can load ``path`` as a structure (by extension)."""
    return Path(path).suffix.lower() in VMD_TOPOLOGY_SUFFIXES


def vmd_structure_name(script_name):
    """File name of the structure written for VMD script ``script_name``."""
    return f"{Path(script_name).stem}_structure.pdb"


def needs_vmd_structure(universe):
    """True if the Universe's topology file exists but VMD cannot read it."""
    name = getattr(universe, "filename", None)
    return bool(name) and not vmd_readable(name)


def write_vmd_structure(universe, output):
    """PDB of all atoms (frame 0) in Universe order, chain/segment IDs kept."""
    reader = universe.trajectory
    old = int(reader.frame)
    try:
        reader[0]  # pylint: disable=pointless-statement
        return write_pdb(universe.atoms, output)
    finally:
        reader[old]  # pylint: disable=pointless-statement


def tcl_quote(text):
    """Quote a string as one Tcl word (braces when possible)."""
    text = str(text)
    if "{" not in text and "}" not in text and not text.endswith("\\"):
        return "{" + text + "}"
    return '"' + re.sub(r'([\\"$\[\]])', r"\\\1", text) + '"'


def index_ranges(indices):
    """Compact VMD index list, e.g. '0 to 9 15 20 to 22'."""
    idx = np.unique(np.asarray(indices, dtype=int))
    if idx.size == 0:
        raise ValueError("no atoms to select")
    runs = np.split(idx, np.flatnonzero(np.diff(idx) != 1) + 1)
    return " ".join(
        str(r[0]) if r[0] == r[-1] else f"{r[0]} to {r[-1]}" for r in runs)


def residue_atom_rows(column_atoms):
    """All atoms of the residues of ``column_atoms`` (sorted by index), and
    the value column of each atom: the b_factors.pdb mapping."""
    col_of = {}
    for j, res in enumerate(column_atoms.resindices.tolist()):
        if res in col_of:
            raise ValueError(f"two value columns in residue index {res}")
        col_of[res] = j
    atoms = column_atoms.residues.atoms
    atoms = atoms[np.argsort(atoms.indices, kind="stable")]
    cols = np.fromiter(
        (col_of[r] for r in atoms.resindices.tolist()), dtype=int,
        count=len(atoms))
    return atoms, cols


def topology_file(universe, label="VMD script"):
    topology = getattr(universe, "filename", None)
    if not topology:
        raise ValueError(f"{label}: could not determine the topology filename")
    topology = Path(topology).resolve()
    if not topology.is_file():
        raise FileNotFoundError(f"{label}: topology file not found: {topology}")
    return topology


def trajectory_files(universe, label="VMD script"):
    reader = universe.trajectory
    files = getattr(reader, "filenames", None)  # ChainReader
    if files is None:
        name = getattr(reader, "filename", None)
        files = [name] if name else []
    files = [Path(p).resolve() for p in files if p is not None]
    if not files:
        raise ValueError(
            f"{label}: could not determine the trajectory filename(s)")
    for path in files:
        if not path.is_file():
            raise FileNotFoundError(
                f"{label}: trajectory file not found: {path}")
    return files


def _tcl_numbers(row, fill):
    if np.issubdtype(row.dtype, np.integer) or row.dtype == bool:
        return " ".join(str(int(v)) for v in row)
    return " ".join(
        f"{v:.6g}" if math.isfinite(v) else f"{fill:g}" for v in row.tolist())


# ---------------------------------------------------------------- VMD


def write_vmd_user_script(
        output, atoms, values, frames, *, columns=None, universe=None,
        topology=None, trajectories=None, n_traj_frames=None, frame_offset=0,
        scale=None, fill=0.0, selection="protein", style="NewCartoon", header=(
            "Auto-generated by glycokit",
            "Bulk per-frame assignment of residue values"), label="VMD script",
        structure_out=None):
    """VMD Tcl script setting the ``user`` field of ``atoms`` per frame.

    :param atoms: AtomGroup that receives the values. Its indices must match
        the topology file loaded in VMD (do not pass atoms of a Merge()d
        Universe together with an explicit ``topology``).
    :param values: (n_rows, n_cols) array; one row per analysed frame.
        A 1-D array is one row.
    :param frames: Trajectory frame of each row.
    :param columns: Value column of each atom; default one atom per column.
        Use :func:`residue_atom_rows` to colour whole residues.
    :param universe: Source of the file names; default ``atoms.universe``.
    :param topology, trajectories: Override the file names.
    :param scale: (min, max) of the User colour scale; default 0 .. max.
    :param fill: Written for NaN / inf (float values only).
    :param structure_out: Where to write a PDB copy when VMD cannot read the
        topology (e.g. .tpr); required in that case.
    :rtype: pathlib.Path
    """
    vals = np.asarray(values)
    if vals.ndim == 1:
        vals = vals[None]
    if vals.ndim != 2:
        raise ValueError(f"values must be 1-D or 2-D, got shape {vals.shape}")
    frames = [int(f) for f in np.atleast_1d(frames)]
    if len(frames) != len(vals):
        raise ValueError(f"{len(vals)} rows of values but {len(frames)} frames")

    if columns is None:
        if len(atoms) != vals.shape[1]:
            raise ValueError(
                f"{len(atoms)} atoms but {vals.shape[1]} columns; "
                "pass columns=")
        columns = np.arange(len(atoms))
    columns = np.asarray(columns, dtype=int)
    if columns.shape != (len(atoms), ):
        raise ValueError("columns needs one entry per atom")
    if columns.size and (columns.min() < 0 or columns.max() >= vals.shape[1]):
        raise ValueError("columns out of range for values")

    # VMD assigns a value list in index order, so sort atoms the same way.
    order = np.argsort(atoms.indices, kind="stable")
    atoms, columns = atoms[order], columns[order]
    if len(np.unique(atoms.indices)) != len(atoms):
        raise ValueError("atoms contains duplicates")

    universe = atoms.universe if universe is None else universe
    source = (
        topology_file(universe, label)
        if topology is None else Path(topology).resolve())
    trajectories = (
        trajectory_files(universe, label)
        if trajectories is None else [Path(t).resolve() for t in trajectories])
    # a single-structure input lists its topology as the trajectory too
    trajectories = [t for t in trajectories if t != source]
    if n_traj_frames is None:
        n_traj_frames = universe.trajectory.n_frames

    topology = source
    if not vmd_readable(source):
        if structure_out is None:
            raise ValueError(
                f"{label}: VMD cannot read {source.name}; pass "
                "structure_out= to write a PDB copy")
        topology = write_vmd_structure(universe, structure_out).resolve()
        header = (
            *header, f"Structure: {topology.name} (written from "
            f"{source.name}, which VMD cannot read)")

    if scale is None:
        finite = vals[np.isfinite(vals)]
        top = float(finite.max()) if finite.size and finite.max() > 0 else 1.0
        scale = (0, top)
    lo, hi = scale

    lines = [f"# {h}" for h in header] + [
        "", f"set molid [mol new {tcl_quote(topology.as_posix())} waitfor all]",
        "",
    ]
    lines += [
        f"mol addfile {tcl_quote(t.as_posix())} waitfor all molid $molid"
        for t in trajectories
    ]
    lines += [
        "", f"mol modselect 0 $molid {selection}",
        f"mol modstyle 0 $molid {style}", "mol modcolor 0 $molid User", "",
        f"set n_traj_frames {int(n_traj_frames)}",
        "set n_vmd_frames [molinfo $molid get numframes]", "",
        "if {$n_vmd_frames == $n_traj_frames + 1} {",
        "    animate delete beg 0 end 0 $molid",
        '    puts "Deleted duplicate first frame."',
        "} elseif {$n_vmd_frames == $n_traj_frames} {",
        '    puts "Frame counts match; no frame deleted."', "} else {",
        (
            '    error "Frame mismatch: VMD has $n_vmd_frames frames, but the '
            "trajectory has $n_traj_frames. Expected equal counts or exactly "
            'one extra VMD frame."'), "}", "", "# Set User color scale",
        f"mol scaleminmax $molid 0 {lo:.10g} {hi:.10g}", "",
        f"set sel [atomselect $molid {{index {index_ranges(atoms.indices)}}}]",
        "",
    ]
    for k, frame in enumerate(frames):
        vmd_frame = frame_offset + frame
        lines += [
            f"# Data frame {k} -> VMD frame {vmd_frame}",
            f"$sel frame {vmd_frame}",
            f"$sel set user {{{_tcl_numbers(vals[k, columns], fill)}}}", "",
        ]
    lines += [
        "$sel delete", 'puts "Finished assigning per-residue user values."', ""
    ]

    output = Path(output)
    output.write_text("\n".join(lines), encoding="utf-8")
    return output


# ---------------------------------------------------------------- ChimeraX


def _cx_quote(path):
    return '"' + Path(path).resolve().as_posix().replace('"', '\\"') + '"'


def write_chimerax_script(
    output, structure, *, color_attribute="bfactor", color_range=None,
    palette="white:red", worm_attribute=None, worm_radii=(0.25, 2.0),
    background_color="lightgray", selection="protein", attribute_files=(),
    comments=()):
    """ChimeraX command script (.cxc) colouring by any attribute.

    :param structure: Structure file opened as model #1.
    :param color_attribute: e.g. ``'bfactor'``, or ``'r:<name>'`` for a
        residue attribute from ``attribute_files``.
    :param color_range: (lo, hi); None lets ChimeraX use the data range.
    :param worm_attribute: Attribute for the worm radius; None = no worm.
    :param attribute_files: .defattr files opened after the structure.
    :rtype: pathlib.Path
    """
    structure = Path(structure).resolve()
    if not structure.is_file():
        raise FileNotFoundError(
            f"ChimeraX script: structure not found: {structure}")
    spec = f"(#1 & {selection})"
    color = f"color byattribute {color_attribute} {spec} palette {palette}"
    if color_range is not None:
        color += f" range {color_range[0]:g},{color_range[1]:g}"
    color += f" noValueColor {background_color}"

    lines = [f"# {c}" for c in comments]
    lines += ["close session", f"open {_cx_quote(structure)}"]
    lines += [f"open {_cx_quote(p)}" for p in attribute_files]
    lines += [
        "hide atoms", "show cartoons", f"color #1 {background_color}", color
    ]
    if worm_attribute:
        r0, r1 = worm_radii
        lines.append(
            f"cartoon byattribute {worm_attribute} {spec} "
            f"min:{r0:g} max:{r1:g}")
    lines.append("view")

    output = Path(output)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output


def _labels(atoms, attr):
    try:
        return [str(v).strip() for v in getattr(atoms, attr)]
    except (AttributeError, NoDataError):
        return [""] * len(atoms)


def write_defattr(output, column_atoms, values, attribute, chain_map=None):
    """ChimeraX residue-attribute file: one value per residue of
    ``column_atoms``; NaN values are skipped."""
    if not (attribute[:1].isalpha() and attribute.replace("_", "").isalnum()):
        raise ValueError(f"invalid attribute name {attribute!r}")
    vals = np.asarray(values, dtype=float)
    if vals.shape != (len(column_atoms), ):
        raise ValueError(
            f"expected {len(column_atoms)} values, got {vals.shape}")
    lines = [
        f"attribute: {attribute}", "match mode: 1-to-1", "recipient: residues"
    ]

    chains = _labels(column_atoms, "chainIDs")
    if chain_map is not None:
        chains = [chain_map.get(c, c) for c in chains]

    keys = zip(
        chains, column_atoms.resids.tolist(), _labels(column_atoms, "icodes"))

    for (chain, resid, icode), v in zip(keys, vals):
        if math.isfinite(v):
            chain_spec = f"/{chain}" if chain else ""
            lines.append(f"\t#1{chain_spec}:{resid}{icode}\t{v:.6g}")
    output = Path(output)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output
